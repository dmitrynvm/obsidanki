// Bundled packages keep their license texts in THIRD_PARTY_NOTICES.md and at the end of main.js.
async function writeNotices(metafile) {
	const packages = new Map();
	for (const input of Object.keys(metafile.inputs)) {
		const match = /^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\//.exec(input);
		if (match && !packages.has(match[1])) packages.set(match[1], match[2]);
	}
	const texts = new Map();
	for (const [dir, name] of [...packages].sort((a, b) => a[1].localeCompare(b[1]))) {
		const manifest = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
		const licenseFile = (await readdir(dir)).find(file => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(file));
		const author = typeof manifest.author === 'string' ? manifest.author : manifest.author?.name;
		let text;
		if (licenseFile) text = (await readFile(path.join(dir, licenseFile), 'utf8')).trim();
		else if (manifest.license === 'MIT' && author) text = `MIT License\n\nCopyright (c) ${author}\n\n${MIT}`;
		else throw new Error(`No license text found for bundled package ${name}`);
		const entry = `${name}@${manifest.version} (${manifest.license})`;
		if (!texts.has(text)) texts.set(text, []);
		if (!texts.get(text).includes(entry)) texts.get(text).push(entry);
	}
	const sections = [...texts].map(([text, entries]) => `${entries.map(entry => `- ${entry}`).join('\n')}\n\n${text}`);
	const notices = `Obsidanki bundles the following third-party software. Each group lists the packages covered by the license text that follows it.\n\n${sections.join('\n\n---\n\n')}\n`;
	await writeFile('THIRD_PARTY_NOTICES.md', `# Third-party software notices\n\n${notices}`);
	await appendFile('main.js', `\n/*! Third-party software notices\n\n${notices.replaceAll('*/', '* /')}*/\n`);
}

if (prod) {
	const result = await context.rebuild();
	await writeNotices(result.metafile);
	process.exit(0);
} else {
	await context.watch();
}
